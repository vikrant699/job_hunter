test("parseOrThrow returns the typed value on success", () => {
  const S = z.object({ a: z.number() });
  assert.deepEqual(parseOrThrow(S, { a: 1 }, { provider: "x", slug: "acme" }), { a: 1 });
});
test("parseOrThrow throws with provider/slug and 'schema' in the message on mismatch", () => {
  const S = z.object({ a: z.number() });
  assert.throws(() => parseOrThrow(S, { a: "no" }, { provider: "x", slug: "acme", what: "list" }),
    /x list response failed schema for acme/);
});
test("parseOrNull returns null on mismatch", () => {
  const S = z.object({ a: z.number() });
  assert.equal(parseOrNull(S, { a: "no" }, { provider: "x", slug: "acme" }), null);
});

// The whole gate exists so a board fetch WAITS out an outage instead of failing and letting the run march on.
test("atsFetchJson waits out a network outage instead of failing the board", async (t) => {
  let online = false;
  t.after(stopConnectivityMonitor);
  startConnectivityMonitor({ intervalMs: 5, downIntervalMs: 5, probe: async () => online });
  await new Promise((r) => setTimeout(r, 20));

  let fetchCalls = 0;
  stubFetch(t, async () => {
    fetchCalls++;
    return jsonResponse({ ok: true });
  });

  let settled = false;
  const pending = atsFetchJson("https://boards.example/jobs").then((v) => {
    settled = true;
    return v;
  });

  await new Promise((r) => setTimeout(r, 30));
  assert.equal(fetchCalls, 0, "must not have touched the network while it was down");
  assert.equal(settled, false, "must still be waiting, not skipped");

  online = true;
  const result = await pending;
  assert.equal(fetchCalls, 1, "resumed exactly once, after recovery");
  assert.deepEqual(result, { ok: true });
});

// A board that answers, even with a block page, proves the connection is fine, so one hostile host must never pause everything else.
test("a blocked board reports success to the monitor and does not pause the run", async (t) => {
  t.after(stopConnectivityMonitor);
  startConnectivityMonitor({ intervalMs: 10_000, downIntervalMs: 10_000, probe: async () => true });
  await new Promise((r) => setTimeout(r, 15));

  stubFetch(t, async () => new Response("<html>Access Denied</html>", { status: 403 }));
  await assert.rejects(atsFetchJson("https://waf.example/jobs"));

  assert.equal(connectivityStatus().down, false, "a 403 is the board's problem, not the network's");
});

// Retry-After is clamped to a 250ms floor (util/httpRetry.ts), which is what keeps these fast enough to assert for real.
test("fetchOk retries a 429 with Retry-After then returns the 200 that follows", async (t) => {
  let calls = 0;
  stubFetch(t, async () => {
    calls++;
    if (calls === 1) return new Response("rate limited", { status: 429, headers: { "Retry-After": "0.25" } });
    return jsonResponse({ ok: true });
  });
  const result = await atsFetchJson("https://x.example/api", { provider: "acme" });
  assert.deepEqual(result, { ok: true });
  assert.equal(calls, 2);
});

test("fetchOk retries a retryable status up to the attempt cap, then throws with the last body", async (t) => {
  let calls = 0;
  stubFetch(t, async () => {
    calls++;
    return new Response(`server exploded on attempt ${calls}`, { status: 503, headers: { "Retry-After": "0.25" } });
  });
  // eslint-disable-next-line @typescript-eslint/no-restricted-types -- a caught/thrown value is `unknown` in TS by design (Standard rule 3)
  await assert.rejects(atsFetchJson("https://x.example/api", { provider: "acme" }), (err: unknown) => {
    assert.ok(err instanceof Error);
    assert.match(err.message, /server exploded on attempt 3/);
    return true;
  });
  assert.equal(calls, 3, "one original attempt plus two retries");
});

test("fetchOk does not retry a non-retryable status like 404", async (t) => {
  let calls = 0;
  stubFetch(t, async () => {
    calls++;
    return new Response("nope", { status: 404 });
  });
  await assert.rejects(atsFetchJson("https://x.example/api", { provider: "acme" }), /acme 404/);
  assert.equal(calls, 1);
});

// Edge-challenge classification must still fire off the FINAL attempt's body — it is what powers the deferred end-of-run retry pass.
test("fetchOk still classifies an edge challenge after exhausting retries", async (t) => {
  let calls = 0;
  stubFetch(t, async () => {
    calls++;
    return new Response(CHALLENGE_PAGE_HTML, { status: 503, headers: { "Retry-After": "0.25" } });
  });
  // eslint-disable-next-line @typescript-eslint/no-restricted-types -- a caught/thrown value is `unknown` in TS by design (Standard rule 3)
  await assert.rejects(atsFetchJson("https://x.example/api", { provider: "acme" }), (err: unknown) => {
    assert.ok(err instanceof Error);
    assert.match(err.message, /an edge refused the request/);
    assert.ok(isInfrastructureFault(err), "must classify as infrastructure so the row is never charged");
    return true;
  });
  assert.equal(calls, 3);
});
