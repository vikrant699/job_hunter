test("atsHttpError: 404 gives a short provider-tagged message", () => {
  const e = atsHttpError("keka", 404, "<html>not found</html>");
  assert.equal(e.message, "keka 404");
});

test("atsHttpError: non-404 includes status and a trimmed body snippet", () => {
  const e = atsHttpError("oracle", 500, "x".repeat(500));
  assert.match(e.message, /^oracle HTTP 500: x+$/);
  assert.ok(e.message.length < 230, "body snippet should be capped at ~200 chars");
});

test("atsHttpError builds 404 and generic errors", () => {
  assert.equal(atsHttpError("phenom", 404, "x").message, "phenom 404");
  assert.match(atsHttpError("phenom", 500, "boom").message, /phenom HTTP 500: boom/);
});

test("atsFetchHtml returns the response body, falling back to the requested URL when res.url is empty", async (t) => {
  // Response's .url is read-only (populated by real fetch), so this exercises the res.url || url fallback.
  stubFetch(t, async () => new Response("<html>hi</html>", { status: 200 }));
  const { html, finalUrl } = await atsFetchHtml("https://example.com/careers", { provider: "phenom" });
  assert.equal(html, "<html>hi</html>");
  assert.equal(finalUrl, "https://example.com/careers");
});

test("atsFetchHtml throws atsHttpError on a non-OK response", async (t) => {
  stubFetch(t, async () => new Response("not found", { status: 404 }));
  // eslint-disable-next-line @typescript-eslint/no-restricted-types -- a caught/thrown value is `unknown` in TS by design (Standard rule 3)
  await assert.rejects(atsFetchHtml("https://example.com/careers", { provider: "keka" }), (err: unknown) => {
    assert.ok(err instanceof Error);
    assert.equal(err.message, "keka 404");
    return true;
  });
});

// atsHttpError keeps only 200 chars of body, truncating before WAF markers - the full body must be scanned for challenge evidence before the snippet is cut.
test("a non-OK response whose body is a WAF block page throws an edge-refusal error, not a board defect", async (t) => {
  const cloudFrontBody =
    `<!DOCTYPE HTML PUBLIC "-//W3C//DTD HTML 4.01 Transitional//EN" "http://www.w3.org/TR/html4/loose.dtd">\n` +
    `<HTML><HEAD><META HTTP-EQUIV="Content-Type" CONTENT="text/html; charset=iso-8859-1">\n` +
    `<TITLE>ERROR: The request could not be satisfied</TITLE>\n</HEAD><BODY>\n<H1>403 ERROR</H1>\n` +
    `<H2>The request could not be satisfied.</H2>\nRequest blocked.\n<PRE>\n` +
    `Generated by cloudfront (CloudFront)\nRequest ID: 8skGKzMvyeMU==\n</PRE>\n</BODY></HTML>`;
  stubFetch(t, async () => new Response(cloudFrontBody, { status: 403 }));
  // eslint-disable-next-line @typescript-eslint/no-restricted-types -- a caught/thrown value is `unknown` in TS by design (Standard rule 3)
  await assert.rejects(atsFetchJson("https://careers.example/api/pcsx/search", { provider: "eightfoldpcs" }), (err: unknown) => {
    assert.ok(err instanceof Error);
    assert.match(err.message, /an edge refused the request/);
    assert.ok(isInfrastructureFault(err), "must classify as infrastructure so the row is never charged");
    return true;
  });
});

test("a non-OK response with a plain body still throws the ordinary HTTP status error", async (t) => {
  stubFetch(t, async () => new Response("permission denied for this endpoint", { status: 403 }));
  // eslint-disable-next-line @typescript-eslint/no-restricted-types -- a caught/thrown value is `unknown` in TS by design (Standard rule 3)
  await assert.rejects(atsFetchJson("https://careers.example/api", { provider: "workday" }), (err: unknown) => {
    assert.ok(err instanceof Error);
    assert.equal(err.message, "workday HTTP 403: permission denied for this endpoint");
    assert.equal(isInfrastructureFault(err), false, "a plain 403 is the board's answer and stays chargeable");
    return true;
  });
});

